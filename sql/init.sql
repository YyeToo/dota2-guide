-- 设置客户端字符集：保证中文字段内容写入时不乱码
-- ⚠️ 5.7 老版本命令行导入务必加 --default-character-set=utf8mb4（详见 README 的环境坑记录）
SET NAMES utf8mb4;

-- 1. 创建数据库（IF NOT EXISTS：已存在则跳过，脚本可重复执行）
--    utf8mb4 是 utf8 的超集，支持完整中文和 Emoji；
--    注意 MySQL 里的 "utf8" 其实是阉割版（最多 3 字节），中文项目一律用 utf8mb4
CREATE DATABASE IF NOT EXISTS dota_guide
    DEFAULT CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

-- 2. 使用该数据库
USE dota_guide;

-- 3. 创建英雄表
--    IF NOT EXISTS：表已存在则跳过，脚本可重复执行
--    COMMENT：字段注释，在图形化工具里会显示，方便以后维护
--    第四阶段（官网对齐）新增列：
--      role       —— 官网 9 种定位标签（核心/辅助/爆发/控制/打野/肉盾/逃生/推进/先手，顿号分隔）
--      pos        —— 号位：1-5号位（本教学站自创体系，官网没有号位概念）
--      attr       —— 主属性：力量/敏捷/智力/全才（官网数据）
--      attack     —— 攻击方式：近战/远程（官网数据）
--      complexity —— 操作复杂度：1 简单/2 中等/3 困难（官网数据，1 = 官网"新手可玩"）
--      avatar     —— 英雄头像图 URL（官网 CDN，直接引用不占本地空间）
--    第五阶段（搜索俗称优化）新增列：
--      alias      —— 英雄俗称/旧译名（顿号分隔，如"剑圣、尤涅若"；搜索框搜俗称要用，官网无此数据）
--    第六阶段（slug 唯一标识）新增列：
--      slug       —— 英雄英文内部名（唯一，如 axe/sven/crystal_maiden；来自官网头像文件名，
--                    教学页"代表英雄"详情链接用，比数字 id 稳定可读）
--    老库请按 README 的升级路径补列，勿重复执行本建表语句
CREATE TABLE IF NOT EXISTS hero (
    id         BIGINT        NOT NULL AUTO_INCREMENT COMMENT '主键，自增（= 官网 hero_id）',
    name       VARCHAR(50)   NOT NULL                COMMENT '英雄名（官网中文名）',
    slug       VARCHAR(64)   NOT NULL DEFAULT ''     COMMENT '英雄英文内部名（唯一，来自官网头像文件名，教学页详情链接用）',
    alias      VARCHAR(200)  NOT NULL DEFAULT ''     COMMENT '英雄俗称/旧译名（顿号分隔，搜索用；官网无此数据）',
    `role`     VARCHAR(50)   NOT NULL                COMMENT '官网 9 定位标签：核心/辅助/爆发/控制/打野/肉盾/逃生/推进/先手',
    pos        VARCHAR(20)   NOT NULL DEFAULT ''     COMMENT '号位：1-5号位（本教学站自创体系，官网无此概念）',
    attr       VARCHAR(10)   NOT NULL DEFAULT ''     COMMENT '主属性：力量/敏捷/智力/全才（官网数据）',
    attack     VARCHAR(10)   NOT NULL DEFAULT ''     COMMENT '攻击方式：近战/远程（官网数据）',
    complexity TINYINT       NOT NULL DEFAULT 1      COMMENT '操作复杂度：1简单/2中等/3困难（官网数据）',
    avatar     VARCHAR(200)  NOT NULL DEFAULT ''     COMMENT '英雄头像图 URL（官网 CDN）',
    intro      VARCHAR(500)  NOT NULL                COMMENT '英雄简介（官网中文版）',
    tips       VARCHAR(1000) NOT NULL                COMMENT '给新手的打法建议（本教学站自写）',
    items      VARCHAR(500)  NOT NULL DEFAULT ''     COMMENT '推荐装备（顿号分隔，本教学站自写）',
    counters   VARCHAR(500)  NOT NULL DEFAULT ''     COMMENT '克制关系与注意事项（本教学站自写）',
    PRIMARY KEY (id),
    UNIQUE KEY uk_slug (slug)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '英雄表（127 名，官网数据）';

-- 注意：`role` 用反引号包起来了 —— role 是 MySQL 8 的保留字（用于数据库"角色"功能），
-- 不加反引号建表会报语法错误；以后在 SQL 里查询 role 列也要记得加反引号。

-- 3.5 创建英雄技能表（一对多的"多"方）
--     hero_id 指向 hero.id：一个英雄（1）对应多条技能（多）
--     教学项目故意不加 FOREIGN KEY 约束：加了之后 TRUNCATE hero 会报错，
--     影响 heroes_full.sql / skills_full.sql"随时重跑"的便利（详见 upgrade_v2.sql 的注释）
--     三列分类事实（第三阶段起，第十一阶段补齐）：
--       skill_type     —— 主动（要按键施放）/ 被动（自动生效，含光环类）
--       skill_category —— 基础 / 魔晶新增 / 神杖新增 / 魔晶强化 / 神杖强化
--                          一列同时说清「哪来的」和「是新增还是纯强化」，
--                          调用方不用再解析技能名后缀去猜
--       is_innate      —— 1 = 先天技能（出生自带，不占按键也不占技能位）
--       按键规则（第三阶段 + 第四阶段官网数据规则）：
--         Q/W/E/R 基础技能；魔晶/神杖"新增技能"占 D/F 键；
--         只"强化已有技能"的按键存空字符串 ''，技能名加 "·魔晶强化"/"·神杖强化" 后缀
--         （先天技能以前靠技能名 "先天·" 前缀标记，第十一阶段改用 is_innate 列，
--           技能名回归干净的原名）
--       sort_order     —— 本行在这个英雄技能列表里的位次，每个英雄都是 1..n 连续。
--                          详情接口直接按它排，不再自己拼 FIELD(...) 排序
--     skill_desc 在第四阶段从 VARCHAR(300) 加宽到 1000：
--       官网技能描述比手写版长（最长的接近 300 字），300 有截断风险
CREATE TABLE IF NOT EXISTS hero_skill (
    id             BIGINT        NOT NULL AUTO_INCREMENT COMMENT '主键，自增',
    hero_id        BIGINT        NOT NULL                COMMENT '所属英雄 id（对应 hero.id，逻辑外键）',
    skill_key      VARCHAR(10)   NOT NULL                COMMENT '按键：Q/W/E/R（R 为大招）；魔晶/神杖新增技能为 D/F，纯强化为空',
    skill_type     VARCHAR(10)   NOT NULL DEFAULT '主动' COMMENT '技能类型：主动/被动（被动自动生效，无需按键）',
    skill_category VARCHAR(10)   NOT NULL DEFAULT '基础' COMMENT '技能分类：基础/魔晶新增/神杖新增/魔晶强化/神杖强化',
    is_innate      TINYINT(1)    NOT NULL DEFAULT 0      COMMENT '是否先天技能：1=先天（出生自带、不占按键），0=否',
    sort_order     INT           NOT NULL DEFAULT 0      COMMENT '在本英雄技能列表里的位次，每个英雄 1..n 连续',
    skill_name     VARCHAR(50)   NOT NULL                COMMENT '技能名（官网中文名，强化行带 ·魔晶强化/·神杖强化 后缀）',
    skill_desc     VARCHAR(1000) NOT NULL                COMMENT '技能效果（官网描述清洗后，最长约 300 字）',
    PRIMARY KEY (id),
    -- 排序键：详情页按「某英雄 + 位次」取技能，这一个索引就全包了。
    -- 它最左前缀就是 hero_id，所以老的单列索引 idx_hero_id 是多余的（第十一阶段删掉）
    UNIQUE KEY uk_hero_order (hero_id, sort_order)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COMMENT = '英雄技能表（与 hero 一对多，795 条官网数据）';

