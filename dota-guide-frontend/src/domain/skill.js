// ============================================================
// domain/skill.js —— 技能的领域谓词
// ============================================================
//
// 这里放开在**一个技能对象**上的判断。和 vocab.js 的分工：
//
//   vocab.js  值 → 界面上显示成什么（徽章文案、CSS 类名）
//   skill.js  值 → 是非题（这个技能算不算"强化类"、算不算"先天"）
//
// 两者都是纯函数、都不碰 Vue，所以都能被 node --test 直接跑。
// 分开是因为判据会被人查询：想知道"什么算强化类"，来这里；
// 想知道"强化类长什么样"，去 vocab.js。

/**
 * 这两个分类是"只强化已有技能、不占新技能位"的。
 *
 * ⚠️ 判据是 skillCategory，不是"skillKey 是不是空字符串"。
 * 物化之前这两者恰好等价，但"按键为空"只是强化类的**副作用**，不是它的定义 ——
 * 真出现"基础技能放不下第 5 个"这种边角时，两者就会不一致。
 * 完整分类见 CONTEXT.md 的「技能分类」。
 */
const UPGRADE_CATEGORIES = ['魔晶强化', '神杖强化']

export function isUpgradeSkill(skill) {
  return UPGRADE_CATEGORIES.includes(skill.skillCategory)
}

/**
 * 是否先天技能（出生自带、随等级自动升级，如剑圣的剑舞）。
 *
 * 后端给的是 1/0（数据库 TINYINT），这里转成布尔 —— 把"数据库用什么表示"
 * 挡在视图外面，模板里就不用写 `=== 1` 这种表示法泄漏的代码。
 *
 * ⚠️ 不看技能名开头的"先天·"前缀。那个前缀是生成器为了把信息塞进名字里打的补丁，
 * 代价是技能名不再是官网原名；现在信息有正经的列了。
 */
export function isInnate(skill) {
  return skill.isInnate === 1
}
