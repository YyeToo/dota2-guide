// ============================================================
// domain/scrollspy.js —— 章节页签"现在读到哪一节"的判定
// ============================================================
//
// 新手须知页现在是【整页纵向滚动】：横幅 → 页签栏 → 第一节 → 第二节 → 第三节。
// 页签栏吸顶（滚动时钉在顶栏下面），同时要反过来告诉用户"你正读到哪一节"：
// 读到哪一节，哪个页签就变金色。
//
// 这个文件只回答一个问题：**给定几节的坐标和一条判定线，该高亮哪个页签。**
//
// 为什么抽成纯函数：
// 它多半会写成"读 getBoundingClientRect → 从头到尾比一遍 → 写 activeSection.value"
// 揉在一个 for 循环里，只能靠滚动页面肉眼验证。抽出来之后只吃数字、只吐字符串，
// node --test 就能把边角情况全钉住（见 test/scrollspy.test.js）——
// 尤其是下面那两条最容易写错的：「判定线正好落在两节的间隙里」和「读到底了」。
//
// ⚠️ 调用方有个约定：算 atBottom 时要带上 `window.scrollY > 0` 这个前提。
//    否则"内容比视口还短、根本滚不动"的页面会一进来就算作"已到底"，
//    于是页面刚打开就把最后一个页签点亮了。

/**
 * 从各章节的矩形里挑出当前该高亮的那一节。
 *
 * @param {{key: string, top: number, bottom: number}[]} rects
 *        各章节的视口坐标（getBoundingClientRect() 的 top/bottom 原样传进来），
 *        **必须按页面上的先后顺序排列**
 * @param {number} line
 *        判定线的 y 坐标（视口坐标系）。
 *        取值 = 吸顶页签栏的 bottom（页签栏的下边缘），
 *        因为那条边正是"正文从这里开始露出来"的位置
 * @param {{atBottom?: boolean}} [opts]
 *        atBottom：页面是否已经滚到底（调用方判断，注意上面那条约定）
 * @returns {string|null} 该高亮的章节 key；还没有任何一节滚到判定线时返回 null
 *
 * 判定规则（按顺序）：
 *   1. 页面已到底 → 屏幕上剩下的最后一节就是读者在看的那节。
 *      单看"判定线在谁里面"在这里会判错：最后一节比较短时，
 *      页面到底时它整个都还在判定线【下面】，读者分明在看它，
 *      高亮却停在已经完全滚出屏幕的倒数第二节上
 *   2. 判定线落在某一节【内部】（top ≤ line < bottom）→ 就是它
 *   3. 都不满足时取"已经滚过判定线"的最后那一节 —— 这一条兜住两种情形：
 *      · 判定线正好落在两节的间隙里（列表有 24px 的 gap）。
 *        没有它，滚动经过间隙的一瞬间会"全部不高亮"，页签上的金色闪一下
 *      · 读者读到这一节中后段，判定线早就划出它的底部了
 *   4. 一段都还没滚到判定线（还在读顶部的横幅）→ 返回 null，谁都不高亮。
 *      这一条是刻意的：页面刚打开就点亮第一个页签，会让人以为"已经在第一节里了"
 */
export function pickActiveSection(rects, line, { atBottom = false } = {}) {
  // 页签栏挂载时就会先算一次，这一刻很可能还没收集到章节元素
  if (!rects.length) return null

  // 规则 1：到底了，就是最后一节
  if (atBottom) return rects[rects.length - 1].key

  let lastPassed = null

  for (const r of rects) {
    // 规则 2：判定线落在这一节里面
    if (r.top <= line && r.bottom > line) return r.key

    // 顺路记下"已经滚过判定线"的最后一节
    // （数组按页面顺序排，所以直接覆盖就是在取最后一个）
    if (r.top <= line) lastPassed = r.key
  }

  // 规则 3 / 4：都没有就是 null
  return lastPassed
}
