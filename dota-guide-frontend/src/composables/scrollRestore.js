// ============================================================
// composables/scrollRestore.js —— 跨路由的"滚动位置补恢复"
// ============================================================
//
// 【为什么需要它】
// 浏览器恢复滚动位置（router/index.js 里 scrollBehavior 的 savedPosition 分支）
// 发生在**路由切换完成的那一刻**。而英雄图鉴页的内容是异步拿回来的 ——
// 那一刻页面上只有骨架屏，整页还不够高，于是：
//
//     window.scrollTo(0, 3000)   // 用户离开时在第 3000 像素
//     → 浏览器把它**钳到当时的页面底部**（实测 606px）
//
// 等数据回来、页面真的变长了，滚动条已经停在那个错误的位置上，
// 没有任何人会再去纠正它。用户看到的就是"返回列表，落在了列表中间某处"。
//
// 所以：路由那边顺手把"本来该落到哪"记在这里，
// 由**知道数据什么时候到**的页面在数据到位后自己补一次。
// 目前只有英雄图鉴页需要走这条路（见 HomeView 的 onMounted）。
// 须知页 / 进阶页的内容是同步渲染的，高度一开始就是对的，
// 直接用 scrollBehavior 返回的 savedPosition 就够了，不会来这里取。
//
// 【为什么不是"列表页自己记住位置、回来时恢复"】
// 那样分不清两种情况：
//   · 用户在详情页点页头导航的"英雄图鉴" —— 这是**新去**列表页，该从顶部看
//   · 用户点"返回列表"或浏览器后退 —— 这是**回到**刚才那一页，该回到原处
// 只有 scrollBehavior 拿到 savedPosition 时才确定是后者，所以判断权在路由那边。

/**
 * 待恢复的滚动位置（像素）。0 表示没有。
 *
 * 故意用一个普通模块级变量而不是 ref：
 * 它只被"写一次、读一次"，没有任何模板依赖它，
 * 做成响应式反而会让人误以为它可以驱动渲染。
 */
let pending = 0

/**
 * 记下"如果有页面需要补恢复，应该落到这个位置"。
 * 只有 router/index.js 的 scrollBehavior 会调用它。
 *
 * 非正数（0 / NaN / 负数）一律当作"没有"：位置为 0 就是顶部，
 * 浏览器本来就恢复对了，不需要谁来补。
 */
export function setPendingScroll(top) {
  pending = Number.isFinite(top) && top > 0 ? top : 0
}

/**
 * 取走待恢复的位置，并把记录清空。
 * 返回 0 表示没有待恢复的位置（调用方直接跳过即可）。
 *
 * ⚠️ 取一次就清空：不清的话，以后每次进列表页都会被这个过期的数字拽走。
 */
export function takePendingScroll() {
  const top = pending
  pending = 0
  return top
}
